/**
 * プリズムの既定の姿勢（TASKS 6-6 段階3）。
 *
 * **依存を 1 つも持たない最下層のモジュール。** Three にも DOM にも store にも触らない。
 * 姿勢の単一の真実は `PrismObject.object.matrixWorld` のままで、ここが持つのは
 * 「起動時とリセット時に置く場所」という定数だけである。
 *
 * ここに切り出す理由は、同じ値を **配線側（`main.ts`）と共有 URL 側
 * （`ui/shareUrl.ts`）の両方**が必要とするからである。定数を 2 か所に書くと、
 * 片方だけ変えたときに「共有 URL の既定」と「アプリの既定」が静かにずれ、
 * 既定のはずの姿勢が URL に載る（あるいはその逆）という分かりにくい壊れ方をする。
 */

/**
 * 意図した既定姿勢：プリズムの Z 軸まわりの回転角 [deg]。
 *
 * リセット（3-7）の戻り先であり、光源の狙点と入射角の較正もこの姿勢を基準に凍結する。
 * 以後プリズムを回してもこの値は動かない（姿勢の現在値は `matrixWorld` が持つ）。
 *
 * **共有 URL の復元は、この角度で凍結を済ませた後に行う。** 凍結前に姿勢を復元すると
 * `entryNormalAngleDeg` の基準が共有者と変わり、同じ回転角でも実測 θ₁ がずれる。
 */
export const DEFAULT_PRISM_ROTATION_DEG = 20;

/** 既定の位置。移動ギズモは XY 面内だけなので z は常に 0。 */
export const DEFAULT_PRISM_X = 0;
export const DEFAULT_PRISM_Y = 0;
