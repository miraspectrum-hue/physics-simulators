/**
 * 半透明レイヤの描画順（TASKS 外の不具合修正）。
 *
 * 床・プリズム・光線はいずれも `transparent: true` で `depthWrite: false` なので、
 * **深度では前後関係が決まらない**。three は半透明オブジェクトをカメラからの距離で
 * 並べ替えるが、光線オブジェクトはバッファを自前で書き換えるためバウンディングが
 * 更新されず（`frustumCulled = false`）、並べ替えの鍵として意味を持たない。
 * つまり既定では**床・ガラス・光線の描画順が規定されない**。
 *
 * ガラスが光線より後に描かれると、通常ブレンドの `1 - opacity` が既に描かれた光線を
 * 減光し、ガラスを通る区間だけ暗く（途切れて）見える。光は加算で最後に足すのが
 * 物理的にも正しいので、順序を明示して固定する。
 */
export const RENDER_ORDER = {
  /** 床。最も奥の演出。 */
  floor: 0,

  /** 仮想スクリーンの板。帯の下地になるので帯より先に描く。 */
  screenPanel: 1,

  /** スクリーンに映るスペクトルの帯。通常ブレンドで板の上に像として乗る。 */
  screenBand: 2,

  /** プリズムのガラス。 */
  prism: 3,

  /** 光線。加算ブレンドなので必ず最後に足す。 */
  beam: 4,
} as const;
